<!-- wp:paragraph {"className":"src"} -->
<p class="src">As its advocates commonly present it. Open a line to read the reply.</p>
<!-- /wp:paragraph -->

<!-- wp:details {"className":"is-style-verdict-granted"} -->
<details class="wp-block-details is-style-verdict-granted"><summary><strong>P1</strong>The Qur’an says the Torah and the Gospel were revealed by God.</summary><!-- wp:paragraph {"className":"reply"} -->
<p class="reply">Agreed. God revealed the Tawrat to Moses and the Injil to Jesus <span class="ref">Q 3:3</span>. The question is what those words refer to.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-verdict-equivocates"} -->
<details class="wp-block-details is-style-verdict-equivocates"><summary><strong>P2</strong>“The Gospel” in the Qur’an means the Bible Christians held in the 7th century.</summary><!-- wp:paragraph {"className":"reply"} -->
<p class="reply">The Qur’an speaks of one Injil <em>given to</em> Jesus. The New Testament is twenty-seven books written <em>about</em> him by others. The argument rests on treating these as the same thing. <a href="/muslim-response/#injil">Read §2</a></p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-verdict-does-not-follow"} -->
<details class="wp-block-details is-style-verdict-does-not-follow"><summary><strong>P3</strong>The Qur’an tells Christians to judge by their scripture, so it must have been intact.</summary><!-- wp:paragraph {"className":"reply"} -->
<p class="reply">“Judge by what God revealed <em>therein</em>” <span class="ref">Q 5:47</span> points to revelation still present in what they held. It does not certify every word. Jesus told his hearers to obey the scribes while condemning their additions <span class="ref">Matt 23:2–3</span>. <a href="/muslim-response/#judge">Read §3</a></p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-verdict-false"} -->
<details class="wp-block-details is-style-verdict-false"><summary><strong>P4</strong>If the Bible was corrupted, God failed to protect His word.</summary><!-- wp:paragraph {"className":"reply"} -->
<p class="reply">Earlier books were <em>entrusted to</em> their scholars <span class="ref">Q 5:44</span>. Only of the Qur’an does God say “We will guard it” <span class="ref">Q 15:9</span>. A trust given to people can be broken by people. <a href="/muslim-response/#trust">Read §4</a></p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"is-style-verdict-unsupported"} -->
<details class="wp-block-details is-style-verdict-unsupported"><summary><strong>C</strong>Therefore Islam is false.</summary><!-- wp:paragraph {"className":"reply"} -->
<p class="reply">Without P2 and P4 the dilemma has nothing left. The Qur’an’s own position is a third option: it confirms what remains true in earlier scripture and judges it <span class="ref">Q 5:48</span>. <a href="/muslim-response/#muhaymin">Read §5</a></p>
<!-- /wp:paragraph --></details>
